def t(text):
    """翻译：中文→英文（如果当前语言是英文）"""
    lang = st.session_state.get("lang", "zh")
    if lang == "zh":
        return text
    return TRANSLATIONS.get(text, text)


def tpl(template, **kwargs):
    """翻译模板字符串（处理f-string类场景）
    例如: tpl("共 {count} 条功能", count=5)
    先将中文模板翻译，再格式化
    """
    lang = st.session_state.get("lang", "zh")
    if lang == "zh":
        return template.format(**kwargs)
    english_template = TRANSLATIONS.get(template, template)
    return english_template.format(**kwargs)


def lang_selector():
    """在侧边栏渲染语言切换器"""
    st.sidebar.divider()
    current = st.session_state.get("lang", "zh")
    options = {"zh": "🇨🇳 中文", "en": "🇺🇸 English"}
    labels = list(options.values())
    idx = list(options.keys()).index(current)
    chosen = st.sidebar.radio("Language / 语言", labels, index=idx, key="lang_radio")
    if chosen:
        new_lang = list(options.keys())[labels.index(chosen)]
        if new_lang != current:
            st.session_state.lang = new_lang
            st.rerun()
